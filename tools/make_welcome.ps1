# Gor om en bild till "Welcome back"-bakgrunden pa startskarmen: beskars till 480:272 runt mitten,
# skalas till 480x272, sparas som JPEG i res/WELCOME.JPG och som bytes i src/welcome.h
# (avkodas med libjpeg vid start, se boot.c).
# Kors i Windows: powershell -ExecutionPolicy Bypass -File tools\make_welcome.ps1 bild.jpg [kvalitet]
param([Parameter(Mandatory = $true)][string]$Source, [int]$Quality = 92)
Add-Type -AssemblyName System.Drawing
$project = Split-Path $PSScriptRoot -Parent

$src = [System.Drawing.Image]::FromFile((Resolve-Path $Source))
$sw = $src.Width; $sh = $src.Height
if ($sw / $sh -gt 480 / 272) { $cw = $sh * 480 / 272; $ch = $sh } else { $cw = $sw; $ch = $sw * 272 / 480 }
$rect = New-Object System.Drawing.RectangleF ([float](($sw - $cw) / 2)), ([float](($sh - $ch) / 2)), ([float]$cw), ([float]$ch)
$bmp = New-Object System.Drawing.Bitmap 480, 272, ([System.Drawing.Imaging.PixelFormat]::Format24bppRgb)
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.InterpolationMode = 'HighQualityBicubic'; $g.PixelOffsetMode = 'HighQuality'
$g.DrawImage($src, (New-Object System.Drawing.RectangleF 0, 0, 480, 272), $rect, [System.Drawing.GraphicsUnit]::Pixel)
$g.Dispose(); $src.Dispose()

# baseline-JPEG (inte progressiv), som libjpeg avkodar snabbt
$codec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object { $_.MimeType -eq 'image/jpeg' }
$params = New-Object System.Drawing.Imaging.EncoderParameters 1
$params.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter ([System.Drawing.Imaging.Encoder]::Quality), ([long]$Quality)
$jpg = Join-Path $project 'res\WELCOME.JPG'
$bmp.Save($jpg, $codec, $params)
$bmp.Dispose()

$bytes = [System.IO.File]::ReadAllBytes($jpg)
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* psp5 - made by 08Weber */')
[void]$sb.AppendLine('/* Generated by tools/make_welcome.ps1 from res/WELCOME.JPG - do not edit by hand.')
[void]$sb.AppendLine(' * Bakgrunden till "Welcome back" pa startskarmen: JPEG, 480x272. */')
[void]$sb.AppendLine("#define WELCOME_JPG_SIZE $($bytes.Length)")
[void]$sb.AppendLine('static const unsigned char WELCOME_JPG[WELCOME_JPG_SIZE] = {')
for ($i = 0; $i -lt $bytes.Length; $i += 24) {
    $n = [Math]::Min(24, $bytes.Length - $i)
    $line = ($bytes[$i..($i + $n - 1)] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ','
    [void]$sb.AppendLine("    $line,")
}
[void]$sb.AppendLine('};')
[System.IO.File]::WriteAllText((Join-Path $project 'src\welcome.h'), $sb.ToString().Replace("`r`n", "`n"))
"res/WELCOME.JPG + src/welcome.h ($($bytes.Length) bytes)"

