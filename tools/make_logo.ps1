# psp5 – made by 08Weber
# Ritar psp5-loggan (tunt "psp", halvfett "5", Bahnschrift) kantutjämnad och sparar den som
# alfakarta i src/logo.h. Körs i Windows: powershell -ExecutionPolicy Bypass -File tools\make_logo.ps1
Add-Type -AssemblyName System.Drawing
$project = Split-Path $PSScriptRoot -Parent
$size = 44; $track = 2.5
$parts = @(@{ t = 'psp'; f = 'Bahnschrift SemiLight' }, @{ t = '5'; f = 'Bahnschrift SemiBold' })

$bmp = New-Object System.Drawing.Bitmap 300, 90
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.Clear([System.Drawing.Color]::Black)
$g.TextRenderingHint = 'AntiAlias'
$fmt = [System.Drawing.StringFormat]::GenericTypographic
$x = 10.0
foreach ($p in $parts) {
    $font = New-Object System.Drawing.Font($p.f, [float]$size, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
    foreach ($ch in $p.t.ToCharArray()) {
        $g.DrawString([string]$ch, $font, [System.Drawing.Brushes]::White, [float]$x, [float]10, $fmt)
        $x += $g.MeasureString([string]$ch, $font, 1000, $fmt).Width + $track
    }
}

# beskär till det som syns, med en bildpunkts marginal
$x0 = 999; $y0 = 999; $x1 = 0; $y1 = 0
for ($y = 0; $y -lt $bmp.Height; $y++) { for ($x = 0; $x -lt $bmp.Width; $x++) {
    if ($bmp.GetPixel($x, $y).R -gt 0) { $x0 = [Math]::Min($x0, $x); $x1 = [Math]::Max($x1, $x); $y0 = [Math]::Min($y0, $y); $y1 = [Math]::Max($y1, $y) }
} }
$x0--; $y0--; $x1++; $y1++
$w = $x1 - $x0 + 1; $h = $y1 - $y0 + 1

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* psp5 - made by 08Weber */')
[void]$sb.AppendLine('/* Generated by tools/make_logo.ps1 - do not edit by hand. Alpha per pixel (0-255). */')
[void]$sb.AppendLine("#define LOGO_W $w")
[void]$sb.AppendLine("#define LOGO_H $h")
[void]$sb.AppendLine('static const unsigned char LOGO_ALPHA[LOGO_W * LOGO_H] = {')
for ($y = $y0; $y -le $y1; $y++) {
    $row = for ($x = $x0; $x -le $x1; $x++) { $bmp.GetPixel($x, $y).R }
    [void]$sb.AppendLine('    ' + ($row -join ',') + ',')
}
[void]$sb.AppendLine('};')
[System.IO.File]::WriteAllText((Join-Path $project 'src\logo.h'), $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
$bmp.Clone((New-Object System.Drawing.Rectangle $x0, $y0, $w, $h), $bmp.PixelFormat).Save((Join-Path $env:TEMP 'psp5_logo_preview.png'))
"logo: $w x $h"
